function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

const I18n = createContext({ lang: "en" as Lang, setLang: (_lang: Lang) => undefined as void, t: (key: string, _vars?: Record<string, string | number>) => key });

export function MobileI18n({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    void SecureStore.getItemAsync(KEY).then((stored) => {
      if (stored === "zh" || stored === "en") setLangState(stored);
    });
  }, []);
  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    void SecureStore.setItemAsync(KEY, next);
  }, []);
  const t = useCallback((key: string, vars?: Record<string, string | number>) => fill((lang === "zh" ? zh : en)[key] || en[key] || key, vars), [lang]);
  return <I18n.Provider value={{ lang, setLang, t }}>{children}</I18n.Provider>;
}

export function useT() {
  return useContext(I18n);
}
